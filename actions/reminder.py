import json
import os
import subprocess
import sys
from datetime import datetime
from pathlib import Path

_CNW: dict = {"creationflags": subprocess.CREATE_NO_WINDOW}

# The longest text a reminder may carry. The same limit the sanitiser
# applies, and it is checked BEFORE anything is written: a text that is
# too long is refused, not truncated.
_MAX_MESSAGE = 200

def _base_dir() -> Path:
    if getattr(sys, "frozen", False):
        return Path(sys.executable).parent
    return Path(__file__).resolve().parent.parent


def _scripts_dir() -> Path:
    d = Path.home() / ".teemo" / "reminders"
    d.mkdir(parents=True, exist_ok=True)
    return d


def _sanitise(text: str, max_len: int = _MAX_MESSAGE) -> str:
    return (
        text.replace("\\", "")
            .replace('"', "")
            .replace("'", "")
            .replace("\n", " ")
            .replace("\r", "")
            .strip()
    )[:max_len]

def _write_notify_script(task_name: str, message: str) -> Path:
    script_path = _scripts_dir() / f"{task_name}.py"
    msg_literal = json.dumps(message)

    notify_block = f"""
message = {msg_literal}
notified = False

try:
    from plyer import notification
    notification.notify(title="T.E.E.M.O. Reminder", message=message, timeout=15)
    notified = True
except Exception:
    pass

if not notified:
    try:
        # The package that draws the toast on Windows announces itself
        # with a deprecation warning about pkg_resources, and that
        # warning is the only thing that was ever seen on the console of
        # the reminder. The toast is what the owner asked for.
        import warnings
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            from win10toast import ToastNotifier
        ToastNotifier().show_toast("T.E.E.M.O. Reminder", message, duration=15, threaded=False)
        notified = True
    except Exception:
        pass

if not notified:
    try:
        import subprocess
        # `msg.exe` is a console program: launched without this flag it
        # opens a black window on the desktop for a fraction of a second,
        # and the reminder is not the place for a window to appear.
        subprocess.run(
            ["msg", "*", "/TIME:30", message],
            check=False,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
    except Exception:
        pass

try:
    import winsound
    for freq in [800, 1000, 1200]:
        winsound.Beep(freq, 180)
        import time; time.sleep(0.08)
except Exception:
    pass
"""

    script_body = f"""# Auto-generated by the T.E.E.M.O. reminder — do not edit
import sys, os, pathlib
{notify_block}
# Self-delete after firing
try:
    _self = pathlib.Path(__file__)
    _self.unlink(missing_ok=True)
    # And the launcher that started it, if there was one. Only this
    # task's own launcher: another reminder may be waiting for it.
    _launcher = _self.with_name(_self.stem + "_launcher.vbs")
    if _launcher.exists():
        _launcher.unlink(missing_ok=True)
except Exception:
    pass
"""
    script_path.write_text(script_body, encoding="utf-8")
    script_path.chmod(0o600)   # owner read/write only
    return script_path

def _schedule_windows(target_dt: datetime, task_name: str,
                      script_path: Path, message: str) -> str:
    python_exe = Path(sys.executable)
    pythonw = python_exe.parent / "pythonw.exe"

    # THE RECORDATOR DOES NOT OPEN A CONSOLE.
    #
    # There are two ways to run a program without a window of its own:
    # `pythonw.exe`, which is a copy of python that has no console at all,
    # and `wscript.exe`, which is a host of scripts that has none either.
    #
    # This Python has no `pythonw.exe` next to it — there are installs
    # that do not — so the task was launched with `python.exe` and every
    # reminder opened a black window on the desktop, with a warning from
    # a package that has nothing to do with the reminder in it. That is
    # the window the owner kept seeing.
    #
    # So: `pythonw.exe` when it is there, and a VBScript launcher that
    # runs python hidden when it is not. The Windows Script Host has been
    # in the system since Windows 95.
    if pythonw.exists():
        command = str(pythonw)
        arguments = f'"{script_path}"'
    else:
        launcher_path = _scripts_dir() / f"{task_name}_launcher.vbs"
        vbs = (
            'Set sh = CreateObject("WScript.Shell")\r\n'
            f'sh.Run """{python_exe}"" ""{script_path}""", 0, False\r\n'
        )
        launcher_path.write_text(vbs, encoding="utf-8")
        command = "wscript.exe"
        arguments = f'"{launcher_path}"'

    xml_path = _scripts_dir() / f"{task_name}.xml"
    xml_content = (
        '<?xml version="1.0" encoding="UTF-16"?>\n'
        '<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">\n'
        '  <RegistrationInfo><Description>T.E.E.M.O. Reminder</Description></RegistrationInfo>\n'
        '  <Triggers><TimeTrigger>\n'
        f'    <StartBoundary>{target_dt.strftime("%Y-%m-%dT%H:%M:%S")}</StartBoundary>\n'
        '    <Enabled>true</Enabled>\n'
        '  </TimeTrigger></Triggers>\n'
        '  <Actions><Exec>\n'
        f'    <Command>{command}</Command>\n'
        f'    <Arguments>{arguments}</Arguments>\n'
        '  </Exec></Actions>\n'
        '  <Settings>\n'
        '    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>\n'
        '    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>\n'
        '    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>\n'
        '    <StartWhenAvailable>true</StartWhenAvailable>\n'
        '    <ExecutionTimeLimit>PT5M</ExecutionTimeLimit>\n'
        '    <Enabled>true</Enabled>\n'
        '  </Settings>\n'
        '  <Principals><Principal>\n'
        '    <LogonType>InteractiveToken</LogonType>\n'
        '    <RunLevel>LeastPrivilege</RunLevel>\n'
        '  </Principal></Principals>\n'
        '</Task>'
    )

    xml_path.write_text(xml_content, encoding="utf-16")

    result = subprocess.run(
        ["schtasks", "/Create", "/TN", task_name, "/XML", str(xml_path), "/F"],
        capture_output=True, text=True, encoding="utf-8", errors="replace", **_CNW,
    )

    try:
        xml_path.unlink(missing_ok=True)
    except Exception:
        pass

    if result.returncode != 0:
        script_path.unlink(missing_ok=True)
        err = (result.stderr or result.stdout).strip()
        print(f"[Reminder] ❌ schtasks: {err}")
        return ""  

    return task_name


def reminder(
    parameters: dict,
    response=None,
    player=None,
    session_memory=None,
) -> str:

    date_str = parameters.get("date", "").strip()
    time_str = parameters.get("time", "").strip()
    message  = parameters.get("message", "Reminder").strip()

    if not date_str or not time_str:
        return "I need both a date and a time to set a reminder."

    try:
        target_dt = datetime.strptime(f"{date_str} {time_str}", "%Y-%m-%d %H:%M")
    except ValueError:
        return "I couldn't parse that date or time. Please use YYYY-MM-DD and HH:MM."

    if target_dt <= datetime.now():
        return "That time has already passed — I can't set a reminder in the past."

    # THE TEXT IS CHECKED BEFORE ANYTHING IS WRITTEN.
    #
    #     A text that is too long is refused, not truncated: a reminder that
    #     says less than it was told is worse than no reminder at all. And it
    #     is refused BEFORE the script is written and BEFORE the task is
    #     registered, because a task that is registered and then abandoned
    #     is a task that fires later and shows a message that nobody asked
    #     for.
    #
    #     It also happened here, and it was not the tests' fault alone: a
    #     rejected reminder still left a real scheduled task on the machine
    #     of whoever ran the suite — one per run — and those tasks went on
    #     firing long after the tests were over. That is where the console
    #     windows that appeared every now and then came from.
    if len(message) > _MAX_MESSAGE:
        return (f"status=failed: the reminder text is too long "
                f"({len(message)} characters; the maximum is {_MAX_MESSAGE}).")

    safe_msg   = _sanitise(message)
    task_name  = f"TEEMOReminder_{target_dt.strftime('%Y%m%d_%H%M%S')}"

    # The phone copy is made first and independently: if this machine's
    # scheduler fails, the reminder still reaches the phone, and the other way
    # round. Nothing happens here unless the cloud agent is paired.
    phone = _mirror_to_cloud(message, target_dt)
    # The assistant also says it aloud at that moment when it is running — a
    # routine (core/routines), independent of the system notification below.
    phone += _add_spoken_routine(message, target_dt)

    try:
        script_path = _write_notify_script(task_name, safe_msg)
    except Exception as e:
        return f"Could not prepare the reminder script: {e}{phone}"

    try:
        job_id = _schedule_windows(target_dt, task_name, script_path, safe_msg)
    except Exception as e:
        script_path.unlink(missing_ok=True)
        print(f"[Reminder] ❌ Scheduling exception: {e}")
        return f"Something went wrong while scheduling the reminder.{phone}"

    if not job_id:
        return f"I couldn't register the reminder with the system scheduler.{phone}"

    if player:
        player.write_log(f"[Reminder] ✅ {date_str} {time_str} — {safe_msg[:40]}")

    friendly_time = target_dt.strftime("%B %d at %I:%M %p")
    return f"Reminder set for {friendly_time}.{phone}"


def _add_spoken_routine(message: str, target_dt: datetime) -> str:
    try:
        from core.routines import desktop
        eng = desktop.engine()
        if eng is None:
            return ""
        eng.add(name=message[:60] or "Reminder", kind="say", text=message,
                trigger={"type": "time", "rule": {"type": "once", "at_ts": target_dt.timestamp()}},
                source="reminder")
        return " It will also be said aloud at that time while the assistant is running."
    except Exception as e:
        print(f"[Reminder] spoken copy not set: {e}")
        return ""


def _mirror_to_cloud(message: str, target_dt: datetime) -> str:
    """Also schedule the reminder on the cloud body, so it reaches the phone
    over Telegram even if this computer is off at that time.

    Deterministic on purpose: which of two reminder tools a model happens to
    pick must not decide whether the phone hears about it. Returns a sentence
    to append to the result, or "" when no cloud is paired — in which case this
    costs one config read and changes nothing."""
    try:
        from memory.config_manager import get_plugin_config, get_plugin_enabled
        if not (str(get_plugin_config("cloud_agent").get("pair_code") or "").strip()
                and get_plugin_enabled("cloud_agent")):
            return ""
        agent = sys.modules.get("plugins.cloud_agent")
        if agent is None or not hasattr(agent, "mirror_reminder"):
            return ""
        ok, detail = agent.mirror_reminder(message, target_dt.strftime("%Y-%m-%d %H:%M"))
    except Exception as e:
        ok, detail = False, str(e)
    if ok:
        return " It will also be sent to the user's phone over Telegram at that time."
    return f" The phone copy could not be set ({detail}) — only this computer will remind them."


