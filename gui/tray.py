"""
gui/tray.py — the assistant's face when nothing else is on screen.

WHAT THE ICON IS FOR
    It is the way back. The assistant can be in the corner as a small core,
    or gone from the screen entirely with the conversation still running;
    the icon is what puts the window back in front of the user without
    hunting for it in the taskbar.

THE MENU IS THE THREE THINGS A TRAY ICON IS EXPECTED TO HAVE
    The window, the big window, and the way out. Nothing else, because a
    menu full of novelties is a menu nobody reads.

    The icon's tooltip carries the state, so the assistant is one hover
    away from saying what it is doing even when it is not on screen.
"""
from __future__ import annotations

from pathlib import Path

from PyQt6.QtGui import QAction, QIcon
from PyQt6.QtWidgets import QMenu, QSystemTrayIcon

from core.localization import t as _t

_ICON_PATH = Path(__file__).resolve().parent.parent / "config" / "teemo.ico"


def available() -> bool:
    """Is there a notification area to put an icon in?

    Not on every desktop: a headless session has no tray, and asking for
    one there is a warning on every start. The offscreen and minimal
    platforms are counted as headless even when the machine behind them
    has a shell: those platforms are what a test process and a render
    farm use, and an icon that nobody can click is not an icon.
    """
    try:
        from PyQt6.QtGui import QGuiApplication
        platform = str(QGuiApplication.platformName() or "").lower()
        if platform in ("offscreen", "minimal", "vnc"):
            return False
        return bool(QSystemTrayIcon.isSystemTrayAvailable())
    except Exception:
        return False


class TrayPresence:
    """The icon in the notification area, and the menu it carries."""

    def __init__(self, window, on_show=None, on_maximize=None, on_exit=None):
        self._window = window
        self._on_show = on_show
        self._on_maximize = on_maximize
        self._on_exit = on_exit
        self._state = ""

        self._icon = QSystemTrayIcon(window)
        self._menu = QMenu()

        self._act_window = QAction(_t("tray.window"), self._menu)
        self._act_window.triggered.connect(self._show_window)
        self._act_maximize = QAction(_t("tray.maximize"), self._menu)
        self._act_maximize.triggered.connect(self._maximize_window)
        self._act_exit = QAction(_t("tray.exit"), self._menu)
        self._act_exit.triggered.connect(self._exit_app)

        self._menu.addAction(self._act_window)
        self._menu.addAction(self._act_maximize)
        self._menu.addSeparator()
        self._menu.addAction(self._act_exit)

        self._icon.setContextMenu(self._menu)
        self._icon.activated.connect(self._activated)
        self._set_icon()
        self.set_state("")

    # ── the icon ────────────────────────────────────────────────────────────

    def _set_icon(self) -> None:
        icon = QIcon()
        if _ICON_PATH.exists():
            icon = QIcon(str(_ICON_PATH))
        if icon.isNull():
            # The .ico is generated by the window on first run; ask for it
            # rather than shipping a picture of an old face.
            try:
                from gui.window import MainWindow
                MainWindow._build_teemo_icon(_ICON_PATH)
            except Exception:
                pass
            if _ICON_PATH.exists():
                icon = QIcon(str(_ICON_PATH))
        self._icon.setIcon(icon)

    def show(self) -> None:
        self._icon.show()

    def hide(self) -> None:
        self._icon.hide()

    def set_state(self, state: str) -> None:
        """The tooltip: the name, and what the assistant is doing."""
        self._state = str(state or "")
        name = ""
        try:
            name = str(self._window._assistant_name or "T.E.E.M.O.")
        except Exception:
            name = "T.E.E.M.O."
        if self._state:
            self._icon.setToolTip(f"{name} — {self._state}")
        else:
            self._icon.setToolTip(name)

    # ── the menu ────────────────────────────────────────────────────────────

    def _show_window(self) -> None:
        if self._on_show is not None:
            self._on_show()

    def _maximize_window(self) -> None:
        if self._on_maximize is not None:
            self._on_maximize()

    def _exit_app(self) -> None:
        if self._on_exit is not None:
            self._on_exit()

    def _activated(self, reason) -> None:
        """A click on the icon brings the window back.

        Only a plain click counts: a double click is the same click twice,
        and a middle click is not an invitation.
        """
        try:
            trigger = QSystemTrayIcon.ActivationReason.Trigger
        except AttributeError:
            return
        if reason == trigger:
            self._show_window()
